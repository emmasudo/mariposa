"""
The fuel-id generated by Cazamariposas needs to be resolved into a valid Rust path.

Example: the SMT fix may mention "lib!spec_t.mmu.defs.impl&%19.entry_size" which is not a
valid Rust path to reveal/broadcast use. We use the VIR (and source if necessary) to
resolve this to "crate::spec_t::mmu::defs::Arch::entry_size"

We also need to figure out whether this path needs reveal(...) (for spec fns),
broadcast use ... (for a broadcast fact), or hide(...).

Given a fuel-id and project, this module resolves the path and inserts the statement into the correct Verus function.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path
from typing import List, NamedTuple, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from utils.query_utils import find_verus_procedure_name

VERUS_SOURCE = Path(os.environ.get("VERUS_SOURCE", Path.home() / "verus" / "source"))
VERUS_BIN_DIR = VERUS_SOURCE / "target-verus/release"
VSTD_SRC_ROOT = VERUS_SOURCE / "vstd"


class Unresolved(Exception):
    """
    A fuel-id that could not be traced to a function.
    """


class Resolved(NamedTuple):
    """
    A fuel-id that was traced to a function, and how to expose it.

    `path` is writable Rust. `mode` is the function's Verus mode.
    `broadcast` marks a broadcast_forall fact.
    """

    path: str
    mode: str
    broadcast: bool

    def statement(self, verb: str = "reveal") -> str:
        """
        The Verus statement that exposes this fact/fuel-id.
        """
        if self.broadcast:
            return f"broadcast use {self.path};"
        return f"{verb}({self.path});"


# ---------------------------------------------------------------------------
# Project metadata
# 
# Information about the project that help us resolve the fuel-id (its VIR
# dump, its crate name, and any renaming the fuel-id will require).
# ---------------------------------------------------------------------------

def get_vir(proj_path: str) -> str:
    """
    The project's VIR dump as text using `cargo verus focus` which leaves the
    result on disk at <proj>/vir_dump/crate.vir.

    Raises RuntimeError if the build did not produce a dump, which might mean
    that the crate needs different feature flags.
    """
    vir_path = Path(proj_path) / "vir_dump" / "crate.vir"
    if not vir_path.exists():
        vir_path.parent.mkdir(parents=True, exist_ok=True)
        cargo = (Path(proj_path) / "Cargo.toml").read_text()
        cmd = ["cargo", "verus", "focus"]
        if re.search(r"^verus\s*=", cargo, re.M):
            cmd += ["--features", "verus"]
        cmd += ["--", "--log", "vir", "--log-dir", str(vir_path.parent)]
        env = {**os.environ, "PATH": f"{VERUS_BIN_DIR}:{os.environ['PATH']}"}
        result = subprocess.run(cmd, cwd=proj_path, env=env)
        if not vir_path.exists():
            raise RuntimeError(
                f"build did not produce {vir_path} (exit {result.returncode}); "
                "check --features/--no-default-features for this project"
            )
    return vir_path.read_text()


def get_crate_name(proj_path: str) -> Optional[str]:
    """
    The name this crate is known by elsewhere, or None if it has none.
    """
    try:
        cargo = (Path(proj_path) / "Cargo.toml").read_text()
    except OSError:
        return None
    match = re.search(r'^name\s*=\s*"([^"]+)"', cargo, re.M)
    return match.group(1) if match else None


def to_crate_relative(path: str, crate_name: Optional[str]) -> str:
    """
    Rewrite references to this crate as `crate::`, which is how it names itself.
    """
    if not crate_name:
        return path
    return re.sub(rf"(?<![:\w]){re.escape(crate_name)}::", "crate::", path)


# ---------------------------------------------------------------------------
# Resolution from the VIR dump
#
# Each function has a declaration entry holding information about the mode
# (and for methods, its type).
# ---------------------------------------------------------------------------

MODE_RE = re.compile(r":mode\s+(\w+)")
BROADCAST_RE = re.compile(r":broadcast_forall\s+true")
KIND_RE = re.compile(r":kind \(FunctionKind\s+(\w+)")
TRAIT_IMPL_RE = re.compile(
    r":trait_path\s+([\w:]+)\s*:trait_typ_args\s*\(\("
    r"(?:Typ Datatype\s*\(Dt Path ([\w:]+)\)|Typ Int \(IntRange (\w) (\d+)\))"
)
# Ordered: a `&self` receiver is Ref-decorated, and matching the bare form
# first would skip past it and capture an unrelated later type instead.
SELF_TYPE_RES = (
    re.compile(r'VarIdent "self".*?:typ\s+\(Typ Decorate \(TypDecoration Ref\) '
               r'None \(Typ Datatype\s*\(Dt Path ([\w:]+)\)', re.S),
    re.compile(r'VarIdent "self".*?:typ\s+\(Typ Datatype\s*\(Dt Path ([\w:]+)\)', re.S),
)


def _find_decl(path: str, vir_text: str) -> Optional[int]:
    """
    Find where the path's declaration entry begins in the dump, or None if absent.
    """
    idx = vir_text.find(f":name (Fun :path {path})")
    if idx == -1 or ":kind (FunctionKind" not in vir_text[idx:idx + 200]:
        return None
    return idx


def _read_mode(vir_text: str, idx: int) -> Tuple[str, bool]:
    """
    The mode and broadcast flag of the declaration beginning at `idx`.
    """
    mode = MODE_RE.search(vir_text, idx, idx + 3000).group(1).lower()
    attrs = vir_text.find(":attrs (FunctionAttrs", idx)
    broadcast = attrs != -1 and BROADCAST_RE.search(vir_text, attrs, attrs + 200) is not None
    return mode, broadcast


def _impl_self_type(entry: str, method: str) -> Optional[str]:
    """
    The type owning `method`, read from its declaration entry, or None.
    (This is what replaces an `impl&%N` segment.)
    """
    kind = KIND_RE.search(entry).group(1)
    if kind == "TraitMethodImpl":
        match = TRAIT_IMPL_RE.search(entry)
        if not match:
            return None
        trait_path, datatype, sign, bits = match.groups()
        concrete = datatype or ("u" if sign == "U" else "i") + bits
        return f"<{concrete} as {trait_path}>::{method}"
    if kind == "Static":
        for pattern in SELF_TYPE_RES:
            match = pattern.search(entry)
            if match:
                return f"{match.group(1)}::{method}"
    return None


def resolve(path: str, proj_path: str, vir_text: str) -> Resolved:
    """
    Trace a fuel-id to a writable path and the statement form it needs.

    If the VIR dump omits any information (e.g. _impl_self_type returns None),
    then the source is consulted. Raises Unresolved when neither strategies work.
    """
    idx = _find_decl(path, vir_text)
    if idx is None:
        gap = f"{path}: no declaration in the VIR dump"
    else:
        mode, broadcast = _read_mode(vir_text, idx)
        if "impl&" not in path:
            return Resolved(path, mode, broadcast)
        resolved = _impl_self_type(vir_text[idx:idx + 2000], path.rsplit("::", 1)[-1])
        if resolved is not None:
            return Resolved(resolved, mode, broadcast)
        gap = f"{path}: VIR declaration carries no usable self type"

    found = scan_source(path, proj_path)
    if found is None:
        raise Unresolved(f"{gap}, and no conclusive match in source")
    return found


# ---------------------------------------------------------------------------
# Resolution from source
#
# For fuel-ids that cannot be resolved by the VIR dump, we analyze the method's 
# declaration in the .rs file. That line carries the mode keywords, and the 
# impl block enclosing it carries the type.
# ---------------------------------------------------------------------------

IMPL_RE = re.compile(r"^impl(<[^>]*>)?\s+(?:([\w:]+)(?:<[^>]*>)?\s+for\s+)?([\w:]+)")
GENERIC_PARAM_RE = re.compile(r"[\w']+")
GLOB_IMPORT_RE = re.compile(r"^\s*use\s+super::(\w+)::\*\s*;", re.M)


def _src_root(crate: str, proj_path: str) -> Optional[Path]:
    """
    The directory holding `crate`'s source, or None if it is not known.
    """
    if crate == get_crate_name(proj_path):
        return Path(proj_path) / "src"
    if crate == "vstd":
        return VSTD_SRC_ROOT
    return None


def _impl_self_name(line: str) -> Optional[Tuple[Optional[str], str]]:
    """
    The trait and type an `impl` line introduces, or None for neither.
    """
    match = IMPL_RE.match(line)
    if not match:
        return None
    generics, trait_name, type_name = match.groups()
    if generics:
        params = {
            found.group()
            for param in generics[1:-1].split(",")
            for found in [GENERIC_PARAM_RE.match(param.strip().lstrip("const ").strip())]
            if found
        }
        if type_name in params:
            return None
    return trait_name, type_name


def _declaring_module(type_name: str, file_path: Path, module_path: str,
                      src_root: Path) -> str:
    """
    The module a type is declared in based on a declaration in this file, 
    an import naming the type, or a glob import whose module declares
    the type. Falls back to the module the impl was found in.
    """
    declaration = re.compile(
        r"^\s*(?:pub\s+)?(?:tracked\s+|ghost\s+)?(?:struct|enum|trait)\s+"
        + re.escape(type_name) + r"\b", re.M)
    text = file_path.read_text(errors="replace")
    if declaration.search(text):
        return module_path

    crate = module_path.split("::", 1)[0]
    named = re.search(
        r"^\s*use\s+super::(\w+)::(?:\{[^}]*\b" + re.escape(type_name)
        + r"\b[^}]*\}|" + re.escape(type_name) + r")\s*;", text, re.M)
    if named:
        return f"{crate}::{named.group(1)}"

    for module in GLOB_IMPORT_RE.findall(text):
        candidate = src_root / f"{module}.rs"
        if candidate.exists() and declaration.search(candidate.read_text(errors="replace")):
            return f"{crate}::{module}"
    return module_path


def _ordered_sources(src_root: Path, module_last: str) -> List[Path]:
    """
    Every .rs file under `src_root`, the one named by the fuel-id first.
    """
    own, rest = [], []
    for file_path in src_root.rglob("*.rs"):
        stem = file_path.name.split(".", 1)[0]
        (own if stem == module_last else rest).append(file_path)
    return own + rest


def scan_source(path: str, proj_path: str) -> Optional[Resolved]:
    """
    Trace a fuel-id by reading source, or None if nothing conclusive is found.

    Looks for the method's declaration, taking the mode from the keywords on
    that line and, when the fuel-id names an impl, the type from the block
    enclosing it.

    None means the crate could not be located, or no declaration was found
    that could be attributed to a type.
    """
    parts = path.split("::")
    src_root = _src_root(parts[0], proj_path)
    if src_root is None:
        return None

    method = parts[-1]
    has_impl = "impl&" in path
    module_path = "::".join(parts[:-2] if has_impl else parts[:-1])
    module_last = parts[-3] if has_impl else parts[-2]

    declaration = re.compile(
        r"\b(?:pub\s+)?(?:open\s+|closed\s+)?(broadcast\s+)?(spec|proof|axiom)\s+fn\s+"
        + re.escape(method) + r"\b")
    group = re.compile(r"\bbroadcast\s+group\s+" + re.escape(method) + r"\b")

    for file_path in _ordered_sources(src_root, module_last):
        lines = file_path.read_text(errors="replace").splitlines()
        for i, line in enumerate(lines):
            if group.search(line):
                return Resolved(path, "proof", True)
            match = declaration.search(line)
            if not match:
                continue
            mode, broadcast = match.group(2), match.group(1) is not None
            if not has_impl:
                return Resolved(path, mode, broadcast)
            if ";" in line and "{" not in line:
                continue
            found = _enclosing_impl(lines, i)
            if found is None:
                continue
            trait_name, type_name = found
            owner = _declaring_module(type_name, file_path, module_path, src_root)
            concrete = f"{owner}::{type_name}"
            resolved = (f"<{concrete} as {module_path}::{trait_name}>::{method}"
                        if trait_name else f"{concrete}::{method}")
            return Resolved(resolved, mode, broadcast)
    return None


def _enclosing_impl(lines: Sequence[str], start: int) -> Optional[Tuple[Optional[str], str]]:
    """
    The impl block containing line `start`, as a trait and type, or None.
    """
    for i in range(start, -1, -1):
        line = lines[i].lstrip()
        if line.startswith("trait "):
            return None
        if line.startswith("impl"):
            return _impl_self_name(line)
    return None


# ---------------------------------------------------------------------------
# Editing the source
#
# Given an SMT query and lifted Verus-level repair statements, find the function
# the query came from and produce that file with the statements at the top of its
# body. The patched text is returned.
# ---------------------------------------------------------------------------


CLAUSE_CONTINUATION_RE = re.compile(
    r"^\s*(?:,|requires\b|recommends\b|ensures\b|returns\b|decreases\b|"
    r"opens_invariants\b|via\b|when\b|default_ensures\b)"
)
VERUS_VERIFIED_PREFIX = "_VERUS_VERIFIED_"
INDENT_RE = re.compile(r"\s*")


def locate_target(smt2_path: str, proj_path: str) -> Tuple[Path, int, str]:
    """
    The file, line and function name the query in `smt2_path` was generated from.

    Raises Unresolved if the query names no procedure, or if the file cannot be found.
    """
    procedure = find_verus_procedure_name(smt2_path)
    if procedure == "no procedure found":
        raise Unresolved(f"{smt2_path}: no procedure found")
    name_line, span_line = procedure.split("\n")
    rel_path, line_no = span_line.rsplit(":", 1)
    func_name = name_line.split(" ", 1)[1].split("::")[-1]
    if func_name.startswith(VERUS_VERIFIED_PREFIX):
        func_name = func_name[len(VERUS_VERIFIED_PREFIX):]
    for base in (Path(proj_path), Path(proj_path).parent):
        candidate = base / rel_path
        if candidate.exists():
            return candidate, int(line_no), func_name
    raise Unresolved(f"{rel_path} is under neither {proj_path} nor its parent")


def find_fn_body(lines: Sequence[str], func_name: str,
                 near_line: int) -> Optional[Tuple[int, int]]:
    """
    Where `fn func_name` is declared, and where its body opens.
    None if no such function is in the file.

    `near_line` is where the query says the function is, which is close but
    not exact.
    """
    fn_re = re.compile(r"\bfn\s+" + re.escape(func_name) + r"\b")
    nearby = set(range(max(0, near_line - 20), min(len(lines), near_line + 20)))
    search_order = sorted(nearby) + [i for i in range(len(lines)) if i not in nearby]
    decl_idx = next((i for i in search_order if fn_re.search(lines[i])), None)
    if decl_idx is None:
        return None

    text = "".join(lines[decl_idx:])
    depth = pos = 0
    while pos < len(text):
        char = text[pos]
        if char in "([{":
            if char == "{" and depth == 0:
                end = _matching_brace(text, pos)
                if CLAUSE_CONTINUATION_RE.match(text[end:end + 80]):
                    pos = end
                    continue
                return decl_idx, decl_idx + text[:pos].count("\n")
            depth += 1
        elif char in ")]}":
            depth -= 1
        pos += 1
    return None


def _matching_brace(text: str, open_pos: int) -> int:
    """
    Where the bracket opened at `open_pos` closes, as the offset just past it.
    """
    depth, pos = 1, open_pos + 1
    while pos < len(text) and depth > 0:
        depth += (text[pos] in "([{") - (text[pos] in ")]}")
        pos += 1
    return pos


def apply_patch(source_path: Path, func_name: str, near_line: int,
                statements: Sequence[str], fuel_default_off: bool = False,
                allow_proof_wrap: bool = True) -> str:
    """
    Applies `statements` to `source_path` at the top of the `func_name`'s body 
    and returns the patched text. Raises Unresolved if the function is
    not in the file.

    `fuel_default_off` adds that attribute to the function, which
    turns off the crate-wide default-fuel axiom for this query. The
    statements restore the facts that the query needs.

    `allow_proof_wrap` puts statements in a proof block if there is no
    enclosing verus! block.
    """
    lines = Path(source_path).read_text().splitlines(keepends=True)
    found = find_fn_body(lines, func_name, near_line)
    if found is None:
        raise Unresolved(f"no `fn {func_name}` in {source_path}")
    decl_idx, body_idx = found

    if fuel_default_off:
        indent = INDENT_RE.match(lines[decl_idx]).group()
        lines.insert(decl_idx, f"{indent}#[verifier::fuel_default_off]\n")
        body_idx += 1

    first_body_line = body_idx + 1
    indent = (INDENT_RE.match(lines[first_body_line]).group()
              if first_body_line < len(lines) else " " * 8)
    if allow_proof_wrap and "verus! {" not in "".join(lines):
        statements = ["proof! {", *statements, "}"]
    lines[first_body_line:first_body_line] = [f"{indent}{s}\n" for s in statements] + ["\n"]
    return "".join(lines)
